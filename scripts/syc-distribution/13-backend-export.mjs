// Writes what the backend's SYC distribution module needs from the frozen Ethereum history, plus test fixtures.
//   node 13-backend-export.mjs <path to rethink-backend checkout>/backend/src/syc-distribution
import fs from "node:fs";
import { load, blockTime, blockNumber } from "./lib.mjs";
const out = process.argv[2]; if (!out) throw new Error("pass the backend module directory");
fs.mkdirSync(out + "/fixtures", { recursive: true });
const res = load("result"), pg = load("polygon-transfers");
// first Polygon block at or after a moment on Ethereum
const head = await blockNumber(137);
const firstBlockAtOrAfter = async (t) => { let lo = 60_000_000, hi = head; while (lo < hi) { const mid = (lo + hi) >> 1; if ((await blockTime(137, mid)) >= t) hi = mid; else lo = mid + 1; } return lo; };
const deposits = [];
for (const d of res.deposits) { const b = await firstBlockAtOrAfter(d.t); deposits.push({ holder: d.holder, amount: d.amount, time: d.time, ethereumTx: d.tx, polygonBlock: b }); console.log(d.time, d.holder.slice(0, 8), "-> polygon block", b); }
const measured = res.lots.filter((l) => l.measured).map((l) => ({ claimed: l.rcTime, weights: l.weights }));
if (measured.length !== 2 || !res.lots[0].measured || !res.lots[1].measured) throw new Error("expected exactly the first two claims to span deposits");
fs.writeFileSync(out + "/syc-distribution.frozen.ts", `// Generated by rethink-frontend-v2 scripts/syc-distribution/13-backend-export.mjs. Do not edit by hand.
//
// sniETH (Ethereum) as it stood before the 8 Sep 2026 incident. That vault takes no more deposits, so its history is
// fixed: the five deposits, and how the first two yield claims are shared between wallets (they span deposits, so their
// split was measured from the staking vault's accrued rewards at each deposit). Every later claim is split by balance.

/** The five sniETH deposits. polygonBlock is the first Polygon block at or after the deposit's Ethereum timestamp. */
export const SNIETH_DEPOSITS: { holder: string; amount: string; time: string; ethereumTx: string; polygonBlock: number }[] = ${JSON.stringify(deposits, null, 2)};

/** Split weights of the first two yield claims, in order of arrival on Polygon. */
export const MEASURED_CLAIM_WEIGHTS: { claimed: string; weights: Record<string, string> }[] = ${JSON.stringify(measured, null, 2)};
`);
const rows = pg.rows.filter((r) => r.token === "WETH" || r.token === "SNI").map((r) => ({ safe: r.safe, token: r.token, dir: r.dir, block: r.block, logIndex: r.logIndex, tx: r.tx, from: r.from, to: r.to, amount: r.amount }));
fs.writeFileSync(out + "/fixtures/polygon-transfers.json", JSON.stringify({ head: pg.head, safes: pg.safes, rows }));
fs.writeFileSync(out + "/fixtures/expected.json", JSON.stringify({ note: "scripts/syc-distribution/06-compute.mjs on the same rows", head: pg.head, total: res.total, incent: res.incent, yield: res.yieldM, grand: res.grand,
  lots: res.lots.map((l) => ({ sni: l.sni, weth: l.weth, left: l.left, swapped: l.swapped, unswapped: l.unswapped })), recycledSni: res.recycledSni, mints: res.mints.length }, null, 2));
console.log("rows", rows.length, "head", pg.head, "written to", out);
